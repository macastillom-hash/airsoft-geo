import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {wrap360,signedBearing,compassFromEvent,cameraNavigation} from '../src/cameraNavigation.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const me={lat:4.445,lng:-75.24,accuracy:10,observedAt:100000};
const dest={lat:4.446,lng:-75.24,name:'Objetivo autorizado'};
assert.equal(wrap360(-45),315);
assert.equal(wrap360(405),45);
assert.equal(signedBearing(0,90),-90);
assert.equal(signedBearing(90,0),90);
assert.equal(signedBearing(350,10),-20);
assert.equal(compassFromEvent({absolute:false,alpha:70}),null,'Un sensor relativo no es una brújula fiable');
assert.equal(compassFromEvent({absolute:true,alpha:90}),270);
assert.equal(compassFromEvent({absolute:true,alpha:90},90),0);
assert.equal(compassFromEvent({webkitCompassHeading:120,webkitCompassAccuracy:10}),120);
assert.equal(compassFromEvent({webkitCompassHeading:120,webkitCompassAccuracy:70}),null);
assert.equal(cameraNavigation(me,null,null,0,100000).state,'no-destination');
assert.equal(cameraNavigation({...me,observedAt:69000},dest,null,0,100000).state,'stale-gps');
assert.equal(cameraNavigation({...me,accuracy:90},dest,null,0,100000).state,'inaccurate-gps');
const north=cameraNavigation(me,dest,null,0,100000);
assert.equal(north.state,'ready');
assert.equal(north.headingAvailable,true);
assert.ok(Math.abs(north.relative)<1);
assert.ok(north.distanceM>100&&north.distanceM<120);
const left=cameraNavigation(me,dest,null,90,100000);
assert.ok(left.relative<-89&&left.relative>-91);
const noCompass=cameraNavigation(me,dest,null,null,100000);
assert.equal(noCompass.state,'ready');
assert.equal(noCompass.headingAvailable,false);
assert.equal(noCompass.relative,null);
const route={points:[[4.445,-75.24],[4.446,-75.24],[4.447,-75.24]],maneuvers:[]};
assert.equal(cameraNavigation({lat:4.445,lng:-75.239,accuracy:10,observedAt:100000},dest,route,0,100000).state,'off-route');
const map=read('src/UnifiedMap.jsx'),nav=read('src/MapNavigation.jsx'),
 camera=read('src/CameraNavigation.jsx'),math=read('src/cameraNavigation.js');
assert.ok(map.includes("const [mapStyle,setMapStyle]=useState('street')"),'Default 2D intacto');
assert.ok(map.includes("cameraOpen&&destination&&<Suspense"),'La cámara se carga bajo petición');
assert.ok(nav.includes("onOpenCamera")&&nav.includes("Cámara en vivo"),'Acceso dentro del mapa');
assert.ok(camera.includes("navigator.mediaDevices.getUserMedia")&&camera.includes("audio:false"),'Sin servicio ni micrófono');
assert.ok(camera.includes("document.visibilityState==='hidden'")&&camera.includes("stream.getTracks().forEach(track=>track.stop())"),'Detención al ocultar');
assert.ok(camera.includes("requestPermission")&&camera.includes("onClick={startCamera}"),'Permisos bajo clic');
assert.ok(camera.includes("No se muestra una flecha")&&camera.includes("Brújula no disponible"),'No inventar flechas');
assert.ok(!camera.includes("window.open(")&&!math.includes("maps.googleapis.com"),'No salir ni depender de Google');
console.log('V5.6 PASS: cámara opcional, GPS, brújula absoluta, privacidad y 2D intacto.');
