-- AIRSOFT GEO V3: ACTIVIDADES Y COORDINACION
-- Migracion aditiva: conserva las 8 tablas y objetos de las fases anteriores.
-- NO volver a ejecutar schema.sql ni migracion_fase2.sql.
BEGIN;

CREATE TABLE IF NOT EXISTS public.activities (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 organizer_id uuid NOT NULL REFERENCES auth.users(id),
 title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 4 AND 90),
 description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
 mode text NOT NULL CHECK (mode IN ('coordination','stealth','intelligence','direct_elimination','capture_flag')),
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','active','finished','cancelled')),
 invite_code text NOT NULL UNIQUE DEFAULT upper(substr(encode(extensions.gen_random_bytes(12),'hex'),1,10)),
 starts_at timestamptz,
 duration_minutes integer NOT NULL DEFAULT 60 CHECK (duration_minutes BETWEEN 15 AND 480),
 respawn_seconds integer NOT NULL DEFAULT 0 CHECK (respawn_seconds IN (0,30,60,120)),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.activity_teams (
 activity_id uuid NOT NULL REFERENCES public.activities(id) ON DELETE CASCADE,
 team_id uuid NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
 side text NOT NULL CHECK (side IN ('alpha','bravo')),
 score integer NOT NULL DEFAULT 0 CHECK (score >= 0),
 created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (activity_id,team_id),
 UNIQUE (activity_id,side)
);

CREATE TABLE IF NOT EXISTS public.activity_participants (
 activity_id uuid NOT NULL,
 team_id uuid NOT NULL,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 display_name text NOT NULL CHECK(char_length(btrim(display_name)) BETWEEN 3 AND 40),
 status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','eliminated','withdrawn')),
 eliminated_at timestamptz,
 joined_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (activity_id,user_id),
 FOREIGN KEY (activity_id,team_id) REFERENCES public.activity_teams(activity_id,team_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.activity_zones (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 activity_id uuid NOT NULL REFERENCES public.activities(id) ON DELETE CASCADE,
 team_id uuid,
 name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 3 AND 80),
 zone_type text NOT NULL CHECK (zone_type IN ('meeting','base','objective','checkpoint')),
 latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
 longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
 radius_m integer NOT NULL DEFAULT 50 CHECK (radius_m BETWEEN 20 AND 500),
 CHECK (zone_type<>'base' OR team_id IS NOT NULL),
 created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY (activity_id,team_id) REFERENCES public.activity_teams(activity_id,team_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS activity_one_base_per_team ON public.activity_zones(activity_id,team_id) WHERE zone_type='base';

CREATE TABLE IF NOT EXISTS public.activity_eliminations (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 activity_id uuid NOT NULL REFERENCES public.activities(id) ON DELETE CASCADE,
 requester_id uuid NOT NULL REFERENCES auth.users(id),
 target_id uuid NOT NULL REFERENCES auth.users(id),
 status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','rejected')),
 created_at timestamptz NOT NULL DEFAULT now(),
 resolved_at timestamptz,
 CHECK (requester_id<>target_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS activity_one_pending_elimination ON public.activity_eliminations(activity_id,target_id) WHERE status='pending';

CREATE TABLE IF NOT EXISTS public.activity_flags (
 activity_id uuid NOT NULL,
 team_id uuid NOT NULL,
 status text NOT NULL DEFAULT 'base' CHECK (status IN ('base','carried')),
 carrier_id uuid REFERENCES auth.users(id),
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (activity_id,team_id),
 FOREIGN KEY (activity_id,team_id) REFERENCES public.activity_teams(activity_id,team_id) ON DELETE CASCADE,
 CHECK ((status='base' AND carrier_id IS NULL) OR (status='carried' AND carrier_id IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.activity_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 activity_id uuid NOT NULL REFERENCES public.activities(id) ON DELETE CASCADE,
 actor_id uuid REFERENCES auth.users(id),
 event_type text NOT NULL CHECK (event_type IN ('started','finished','cancelled','elimination','reinstated','flag_picked','flag_scored','flag_reset')),
 detail text NOT NULL DEFAULT '' CHECK (char_length(detail) <= 240),
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_activity_teams_team ON public.activity_teams(team_id);
CREATE INDEX IF NOT EXISTS idx_activity_participants_user ON public.activity_participants(user_id);
CREATE INDEX IF NOT EXISTS idx_activity_eliminations_target ON public.activity_eliminations(target_id,status);
CREATE INDEX IF NOT EXISTS idx_activity_events_activity ON public.activity_events(activity_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_zones_activity ON public.activity_zones(activity_id);
CREATE INDEX IF NOT EXISTS idx_activity_flags_carrier ON public.activity_flags(carrier_id) WHERE carrier_id IS NOT NULL;

-- Funciones de consulta de permisos. Se requieren SECURITY DEFINER solo para evitar
-- recursividad RLS. Son booleanas y verifican siempre auth.uid().
CREATE OR REPLACE FUNCTION public.f3_activity_visible(p_activity uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT (SELECT auth.uid()) IS NOT NULL AND (
   EXISTS (SELECT 1 FROM public.activities a WHERE a.id=p_activity AND a.organizer_id=(SELECT auth.uid()))
   OR EXISTS (SELECT 1 FROM public.activity_teams at JOIN public.team_members tm ON tm.team_id=at.team_id
              WHERE at.activity_id=p_activity AND tm.user_id=(SELECT auth.uid()))
 );
$$;
CREATE OR REPLACE FUNCTION public.f3_enrolled(p_activity uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT (SELECT auth.uid()) IS NOT NULL AND EXISTS (
  SELECT 1 FROM public.activity_participants ap
  WHERE ap.activity_id=p_activity AND ap.user_id=(SELECT auth.uid()) AND ap.status<>'withdrawn'
 );
$$;
CREATE OR REPLACE FUNCTION public.f3_is_organizer(p_activity uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT (SELECT auth.uid()) IS NOT NULL AND EXISTS (
  SELECT 1 FROM public.activities a WHERE a.id=p_activity AND a.organizer_id=(SELECT auth.uid())
 );
$$;

-- Evitar cambios arbitrarios de estado y de identificadores.
CREATE OR REPLACE FUNCTION public.f3_validate_activity_update()
RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN
 IF NEW.id<>OLD.id OR NEW.organizer_id<>OLD.organizer_id OR NEW.invite_code<>OLD.invite_code THEN
  RAISE EXCEPTION 'No se pueden modificar los identificadores';
 END IF;
 IF OLD.status IN ('finished','cancelled') AND NEW IS DISTINCT FROM OLD THEN
  RAISE EXCEPTION 'La actividad ya está cerrada';
 END IF;
 IF OLD.status='active' AND (NEW.title<>OLD.title OR NEW.mode<>OLD.mode OR NEW.duration_minutes<>OLD.duration_minutes OR NEW.respawn_seconds<>OLD.respawn_seconds OR NEW.starts_at IS DISTINCT FROM OLD.starts_at) THEN
  RAISE EXCEPTION 'No se pueden cambiar las reglas de una actividad activa';
 END IF;
 IF OLD.status='draft' AND NEW.status NOT IN ('draft','scheduled','active','cancelled') OR
    OLD.status='scheduled' AND NEW.status NOT IN ('scheduled','active','cancelled') OR
    OLD.status='active' AND NEW.status NOT IN ('active','finished','cancelled') THEN
  RAISE EXCEPTION 'Transición de estado no permitida';
 END IF;
 IF NEW.status='scheduled' AND NEW.starts_at IS NULL THEN RAISE EXCEPTION 'Asigna fecha antes de programar'; END IF;
 IF OLD.status<>NEW.status AND NEW.status='active' THEN
  IF NOT EXISTS(SELECT 1 FROM public.activity_teams t WHERE t.activity_id=NEW.id) THEN
   RAISE EXCEPTION 'Primero debes asignar un equipo';
  END IF;
  IF NEW.mode IN ('direct_elimination','capture_flag') AND
   (SELECT count(*) FROM public.activity_teams t WHERE t.activity_id=NEW.id)<>2 THEN
   RAISE EXCEPTION 'Esta modalidad requiere dos equipos';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.activity_participants ap WHERE ap.activity_id=NEW.id AND ap.status='active') THEN
   RAISE EXCEPTION 'Primero debe inscribirse al menos un participante';
  END IF;
  IF NEW.mode IN ('direct_elimination','capture_flag') AND EXISTS (
    SELECT 1 FROM public.activity_teams t WHERE t.activity_id=NEW.id
      AND NOT EXISTS (SELECT 1 FROM public.activity_participants ap
        WHERE ap.activity_id=NEW.id AND ap.team_id=t.team_id AND ap.status='active')
  ) THEN
   RAISE EXCEPTION 'Cada equipo debe tener al menos un participante activo';
  END IF;
  IF NEW.mode='capture_flag' AND
   (SELECT count(*) FROM public.activity_zones z WHERE z.activity_id=NEW.id AND z.zone_type='base')<>2 THEN
   RAISE EXCEPTION 'Define las dos bases GPS antes de iniciar';
  END IF;
 END IF;
 NEW.updated_at=now();
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_f3_activity_update ON public.activities;
CREATE TRIGGER trg_f3_activity_update BEFORE UPDATE ON public.activities
FOR EACH ROW EXECUTE FUNCTION public.f3_validate_activity_update();

-- Los eventos y notificaciones se originan en transiciones validadas.
-- Se reutiliza la categoría team_alert para que la V2 siga notificando/vibrando.
CREATE OR REPLACE FUNCTION public.f3_activity_status_event()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_type text;
BEGIN
 IF OLD.status=NEW.status OR NEW.status NOT IN ('active','finished','cancelled') THEN RETURN NEW; END IF;
 v_type:=CASE WHEN NEW.status='active' THEN 'started' WHEN NEW.status='finished' THEN 'finished' ELSE 'cancelled' END;
 INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
 VALUES(NEW.id,(SELECT auth.uid()),v_type,NEW.title);
 INSERT INTO public.app_notifications(user_id,actor_id,category,title,detail)
 SELECT ap.user_id,NEW.organizer_id,'team_alert',
  CASE WHEN v_type='started' THEN 'Actividad iniciada' WHEN v_type='finished' THEN 'Actividad finalizada' ELSE 'Actividad cancelada' END,
  NEW.title
 FROM public.activity_participants ap WHERE ap.activity_id=NEW.id AND ap.status<>'withdrawn'
   AND ap.user_id<>NEW.organizer_id;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_f3_status_event ON public.activities;
CREATE TRIGGER trg_f3_status_event AFTER UPDATE OF status ON public.activities
FOR EACH ROW EXECUTE FUNCTION public.f3_activity_status_event();

-- Crear automáticamente una bandera por equipo sin exponer actualización al cliente.
CREATE OR REPLACE FUNCTION public.f3_flag_on_team_join()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM public.activities a WHERE a.id=NEW.activity_id AND a.mode='capture_flag') THEN
  INSERT INTO public.activity_flags(activity_id,team_id) VALUES(NEW.activity_id,NEW.team_id)
  ON CONFLICT DO NOTHING;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_f3_flag_on_team_join ON public.activity_teams;
CREATE TRIGGER trg_f3_flag_on_team_join AFTER INSERT ON public.activity_teams
FOR EACH ROW EXECUTE FUNCTION public.f3_flag_on_team_join();

-- La eliminación virtual no se completa hasta que la persona destinataria la confirma.
CREATE OR REPLACE FUNCTION public.f3_validate_elimination()
RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE a_status text; a_mode text; at_team uuid; target_team uuid;
BEGIN
 IF TG_OP='INSERT' THEN
  SELECT status,mode INTO a_status,a_mode FROM public.activities WHERE id=NEW.activity_id;
  IF a_mode<>'direct_elimination' OR a_status<>'active' THEN RAISE EXCEPTION 'La actividad de eliminación no está activa'; END IF;
  SELECT team_id INTO at_team FROM public.activity_participants WHERE activity_id=NEW.activity_id AND user_id=NEW.requester_id AND status='active';
  SELECT team_id INTO target_team FROM public.activity_participants WHERE activity_id=NEW.activity_id AND user_id=NEW.target_id AND status='active';
  IF at_team IS NULL OR target_team IS NULL OR at_team=target_team THEN RAISE EXCEPTION 'Solo se permiten capturas entre participantes rivales activos'; END IF;
  IF NEW.status<>'pending' OR NEW.resolved_at IS NOT NULL THEN RAISE EXCEPTION 'La captura debe comenzar pendiente'; END IF;
 ELSE
  IF NEW.id<>OLD.id OR NEW.activity_id<>OLD.activity_id OR NEW.requester_id<>OLD.requester_id OR NEW.target_id<>OLD.target_id OR NEW.created_at<>OLD.created_at THEN
    RAISE EXCEPTION 'No puedes modificar los datos de la captura';
  END IF;
  IF OLD.status<>'pending' OR NEW.status NOT IN ('confirmed','rejected') THEN RAISE EXCEPTION 'Captura ya resuelta'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.activities WHERE id=OLD.activity_id AND status='active') THEN RAISE EXCEPTION 'La actividad ya no está activa'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.activity_participants ap WHERE ap.activity_id=OLD.activity_id AND ap.user_id=OLD.target_id AND ap.status='active') THEN RAISE EXCEPTION 'El participante ya no está activo'; END IF;
  NEW.resolved_at:=now();
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_f3_validate_elimination ON public.activity_eliminations;
CREATE TRIGGER trg_f3_validate_elimination BEFORE INSERT OR UPDATE ON public.activity_eliminations
FOR EACH ROW EXECUTE FUNCTION public.f3_validate_elimination();

CREATE OR REPLACE FUNCTION public.f3_complete_elimination()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF NEW.status='confirmed' AND OLD.status='pending' THEN
  UPDATE public.activity_participants SET status='eliminated',eliminated_at=now()
  WHERE activity_id=NEW.activity_id AND user_id=NEW.target_id AND status='active';
  INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
  VALUES(NEW.activity_id,NEW.requester_id,'elimination','Captura virtual confirmada');
  UPDATE public.activity_flags SET status='base',carrier_id=NULL,updated_at=now()
  WHERE activity_id=NEW.activity_id AND carrier_id=NEW.target_id;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_f3_complete_elimination ON public.activity_eliminations;
CREATE TRIGGER trg_f3_complete_elimination AFTER UPDATE OF status ON public.activity_eliminations
FOR EACH ROW EXECUTE FUNCTION public.f3_complete_elimination();

-- La bandera vuelve automáticamente a su base si el portador se retira.
CREATE OR REPLACE FUNCTION public.f3_release_flag_on_leave()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $airsoft$
