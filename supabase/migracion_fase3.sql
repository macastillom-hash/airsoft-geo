 FOR EACH ROW EXECUTE FUNCTION public.f3_release_flag_on_leave();

-- Acciones de bandera atómicas: GPS reciente y zona autorizada.
-- No se valida antisuplantación: las coordenadas del dispositivo pueden falsificarse.
CREATE OR REPLACE FUNCTION public.f3_flag_action(p_activity uuid,p_flag_team uuid,p_action text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_user uuid:=(SELECT auth.uid()); v_team uuid; v_status text; v_mode text;
 v_flag public.activity_flags%ROWTYPE; v_lat double precision; v_lng double precision; v_accuracy double precision;
 v_at timestamptz; v_zone public.activity_zones%ROWTYPE; v_distance double precision;
BEGIN
 IF v_user IS NULL THEN RAISE EXCEPTION 'Inicia sesión'; END IF;
 SELECT status,mode INTO v_status,v_mode FROM public.activities WHERE id=p_activity;
 IF v_status<>'active' OR v_mode<>'capture_flag' THEN RAISE EXCEPTION 'Esta actividad de bandera no está activa'; END IF;
 SELECT team_id INTO v_team FROM public.activity_participants WHERE activity_id=p_activity AND user_id=v_user AND status='active';
 IF v_team IS NULL OR NOT EXISTS(SELECT 1 FROM public.team_members tm WHERE tm.team_id=v_team AND tm.user_id=v_user) THEN RAISE EXCEPTION 'Debes ser participante activo del equipo'; END IF;
 IF p_action NOT IN ('pickup','score') THEN RAISE EXCEPTION 'Acción desconocida'; END IF;
 SELECT * INTO v_flag FROM public.activity_flags WHERE activity_id=p_activity AND team_id=p_flag_team FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Bandera no encontrada'; END IF;
 IF (p_action='pickup' AND v_team=p_flag_team) OR (p_action='score' AND v_team=p_flag_team) THEN RAISE EXCEPTION 'Debes actuar sobre la bandera rival'; END IF;
 SELECT latitude,longitude,accuracy_m,updated_at INTO v_lat,v_lng,v_accuracy,v_at FROM public.positions WHERE user_id=v_user;
 IF v_at IS NULL OR v_at<now()-interval '60 seconds' OR v_accuracy IS NULL OR v_accuracy>60 THEN
  RAISE EXCEPTION 'Comparte GPS reciente y con precisión de 60 m o mejor';
 END IF;
 IF p_action='pickup' THEN
  IF v_flag.status<>'base' THEN RAISE EXCEPTION 'La bandera no está disponible'; END IF;
  SELECT * INTO v_zone FROM public.activity_zones
   WHERE activity_id=p_activity AND team_id=p_flag_team AND zone_type='base';
 ELSE
  IF v_flag.status<>'carried' OR v_flag.carrier_id<>v_user THEN RAISE EXCEPTION 'No eres el portador'; END IF;
  SELECT * INTO v_zone FROM public.activity_zones
   WHERE activity_id=p_activity AND team_id=v_team AND zone_type='base';
 END IF;
 IF v_zone.id IS NULL THEN RAISE EXCEPTION 'Falta configurar la base GPS'; END IF;
 v_distance:=6371000*2*asin(least(1.0,sqrt(
   power(sin(radians(v_lat-v_zone.latitude)/2),2)+cos(radians(v_zone.latitude))*cos(radians(v_lat))*power(sin(radians(v_lng-v_zone.longitude)/2),2)
 )));
 IF v_distance>v_zone.radius_m THEN RAISE EXCEPTION 'Fuera de la zona de la base (distancia estimada % m)',round(v_distance); END IF;
 IF p_action='pickup' THEN
  UPDATE public.activity_flags SET status='carried',carrier_id=v_user,updated_at=now()
   WHERE activity_id=p_activity AND team_id=p_flag_team;
  INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
  VALUES(p_activity,v_user,'flag_picked','Bandera recogida virtualmente');
  RETURN 'Bandera recogida';
 ELSE
  UPDATE public.activity_flags SET status='base',carrier_id=NULL,updated_at=now()
   WHERE activity_id=p_activity AND team_id=p_flag_team;
  UPDATE public.activity_teams SET score=score+1 WHERE activity_id=p_activity AND team_id=v_team;
  INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
  VALUES(p_activity,v_user,'flag_scored','Captura de bandera registrada');
  INSERT INTO public.app_notifications(user_id,actor_id,team_id,category,title,detail)
  SELECT ap.user_id,v_user,ap.team_id,'team_alert','Punto de captura registrado','Se registró una captura de bandera en la actividad.'
  FROM public.activity_participants ap WHERE ap.activity_id=p_activity AND ap.status='active' AND ap.user_id<>v_user;
  RETURN 'Punto registrado';
 END IF;
END $$;

CREATE OR REPLACE FUNCTION public.f3_organizer_action(p_activity uuid,p_action text,p_user uuid DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_status text;
BEGIN
 IF NOT public.f3_is_organizer(p_activity) THEN RAISE EXCEPTION 'Solo el organizador puede ejecutar esta acción'; END IF;
 SELECT status INTO v_status FROM public.activities WHERE id=p_activity;
 IF v_status<>'active' THEN RAISE EXCEPTION 'La actividad no está activa'; END IF;
 IF p_action='reinstate' THEN
  IF p_user IS NULL THEN RAISE EXCEPTION 'Selecciona un participante'; END IF;
  UPDATE public.activity_participants SET status='active',eliminated_at=NULL
  WHERE activity_id=p_activity AND user_id=p_user AND status='eliminated';
  IF NOT FOUND THEN RAISE EXCEPTION 'El participante no está eliminado'; END IF;
  INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
  VALUES(p_activity,(SELECT auth.uid()),'reinstated','Reincorporación virtual autorizada');
  RETURN 'Participante reincorporado';
 ELSIF p_action='reset_flags' THEN
  UPDATE public.activity_flags SET status='base',carrier_id=NULL,updated_at=now() WHERE activity_id=p_activity;
  INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
  VALUES(p_activity,(SELECT auth.uid()),'flag_reset','Banderas reiniciadas por el organizador');
  RETURN 'Banderas reiniciadas';
 END IF;
 RAISE EXCEPTION 'Acción de administrador desconocida';
END $$;

-- La membresía al segundo equipo se acepta solo por su propietario y con código.
-- Creación atómica: evita actividades huérfanas si falla la asignación del equipo.
CREATE OR REPLACE FUNCTION public.f3_create_activity(p_team uuid,p_title text,p_description text,p_mode text,
 p_starts_at timestamptz,p_duration integer,p_respawn integer)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_activity uuid;
BEGIN
 IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Inicia sesión'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.teams t WHERE t.id=p_team AND t.owner_id=(SELECT auth.uid())) THEN
  RAISE EXCEPTION 'Solo el propietario del equipo puede crear actividades'; END IF;
 INSERT INTO public.activities(organizer_id,title,description,mode,starts_at,duration_minutes,respawn_seconds)
 VALUES((SELECT auth.uid()),p_title,coalesce(p_description,''),p_mode,p_starts_at,p_duration,p_respawn)
 RETURNING id INTO v_activity;
 INSERT INTO public.activity_teams(activity_id,team_id,side) VALUES(v_activity,p_team,'alpha');
 RETURN v_activity;
END $$;

-- Reincorporación voluntaria: el reloj se verifica en PostgreSQL, no en el móvil.
CREATE OR REPLACE FUNCTION public.f3_respawn(p_activity uuid)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_seconds integer; v_at timestamptz;
BEGIN
 IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Inicia sesión'; END IF;
 SELECT respawn_seconds INTO v_seconds FROM public.activities
 WHERE id=p_activity AND status='active' AND mode='direct_elimination';
 IF v_seconds IS NULL OR v_seconds=0 THEN RAISE EXCEPTION 'La reincorporación automática no está habilitada'; END IF;
 SELECT eliminated_at INTO v_at FROM public.activity_participants
 WHERE activity_id=p_activity AND user_id=(SELECT auth.uid()) AND status='eliminated' FOR UPDATE;
 IF v_at IS NULL OR now()<v_at+make_interval(secs=>v_seconds) THEN RAISE EXCEPTION 'Todavía no se cumple el tiempo de reincorporación'; END IF;
 UPDATE public.activity_participants SET status='active',eliminated_at=NULL
 WHERE activity_id=p_activity AND user_id=(SELECT auth.uid()) AND status='eliminated';
 INSERT INTO public.activity_events(activity_id,actor_id,event_type,detail)
 VALUES(p_activity,(SELECT auth.uid()),'reinstated','Reincorporación por tiempo cumplido');
 RETURN 'Ya puedes participar nuevamente';
END $$;

CREATE OR REPLACE FUNCTION public.f3_join_activity_team(p_code text,p_team uuid)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_activity uuid; v_status text; v_count integer;
BEGIN
 IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Inicia sesión'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.teams WHERE id=p_team AND owner_id=(SELECT auth.uid())) THEN
  RAISE EXCEPTION 'Solo el propietario puede inscribir a su equipo'; END IF;
 SELECT id,status INTO v_activity,v_status FROM public.activities WHERE invite_code=upper(btrim(p_code)) FOR UPDATE;
 IF v_activity IS NULL THEN RAISE EXCEPTION 'Código de actividad incorrecto'; END IF;
 IF v_status NOT IN ('draft','scheduled') THEN RAISE EXCEPTION 'La actividad ya no acepta equipos'; END IF;
 IF EXISTS(SELECT 1 FROM public.activity_teams WHERE activity_id=v_activity AND team_id=p_team) THEN RETURN v_activity; END IF;
 SELECT count(*) INTO v_count FROM public.activity_teams WHERE activity_id=v_activity;
 IF v_count>=2 THEN RAISE EXCEPTION 'La actividad ya tiene dos equipos'; END IF;
 INSERT INTO public.activity_teams(activity_id,team_id,side) VALUES(v_activity,p_team,CASE WHEN v_count=0 THEN 'alpha' ELSE 'bravo' END);
 RETURN v_activity;
END $$;

